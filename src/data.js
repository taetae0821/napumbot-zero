function evaluate(picks){
  if(picks.length!==5||picks.some(c=>!c))throw new Error("다섯 항목을 모두 선택하세요.");
  const score=picks.reduce((s,c)=>s+c.s,0);
  const issues=picks.filter(c=>c.s<2);
  const criticals=issues.filter(c=>c.crit);
  const stars=criticals.length?1:score===10?3:score>=6?2:1;
  const lead=criticals[0]||issues.find(c=>c.s===0)||issues[0]||null;
  return{score,stars,issues,criticals,lead,leadId:lead?lead.id:null};
}
